-- Trilha de auditoria das alteracoes de ponto feitas pelo administrador (quem mudou o que e quando). SQL portavel entre
-- PostgreSQL e H2 (modo PostgreSQL), usado nos testes.
--
-- APPEND-ONLY: o servico e a entidade nao tem como atualizar nem excluir um evento. Gravado na mesma transacao da
-- mudanca; se a gravacao falhar, a mudanca e desfeita. Sem dados pessoais: guarda somente identificadores (ator,
-- aplicadores) e dados do proprio ponto, nunca CPF, e-mail ou nome de usuario.

CREATE TABLE ponto_auditoria (
    id                    BIGINT      GENERATED BY DEFAULT AS IDENTITY,
    tenant_id             VARCHAR(60) NOT NULL,
    ponto_id              UUID        NOT NULL,
    -- Usuario (administrador) que fez a mudanca: vem do token.
    ator_id               UUID        NOT NULL,
    acao                  VARCHAR(30) NOT NULL,
    estado_anterior       VARCHAR(20),
    estado_novo           VARCHAR(20) NOT NULL,
    aplicador_anterior_id UUID,
    aplicador_novo_id     UUID,
    -- Conteudo da mudanca (campos alterados na edicao, dados da ativacao etc.); texto curto, so dados do ponto.
    detalhes              VARCHAR(2000),
    ocorrido_em           TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_ponto_auditoria PRIMARY KEY (id),
    CONSTRAINT fk_ponto_auditoria_tenant FOREIGN KEY (tenant_id) REFERENCES tenant (id),
    CONSTRAINT fk_ponto_auditoria_ponto FOREIGN KEY (ponto_id, tenant_id) REFERENCES ponto (id, tenant_id),
    CONSTRAINT fk_ponto_auditoria_ator FOREIGN KEY (ator_id, tenant_id) REFERENCES usuario (id, tenant_id),
    CONSTRAINT fk_ponto_auditoria_aplicador_anterior FOREIGN KEY (aplicador_anterior_id, tenant_id)
        REFERENCES usuario (id, tenant_id),
    CONSTRAINT fk_ponto_auditoria_aplicador_novo FOREIGN KEY (aplicador_novo_id, tenant_id)
        REFERENCES usuario (id, tenant_id),
    CONSTRAINT ck_ponto_auditoria_acao CHECK (acao IN ('CRIACAO', 'EDICAO', 'ATRIBUICAO_APLICADOR',
        'REMOCAO_APLICADOR', 'ATIVACAO', 'DESATIVACAO', 'REATIVACAO', 'CANCELAMENTO')),
    CONSTRAINT ck_ponto_auditoria_estado_anterior CHECK (estado_anterior IS NULL
        OR estado_anterior IN ('ENDERECADA', 'DIRECIONADA', 'ATIVA', 'INATIVA', 'DESATIVADO')),
    CONSTRAINT ck_ponto_auditoria_estado_novo CHECK (
        estado_novo IN ('ENDERECADA', 'DIRECIONADA', 'ATIVA', 'INATIVA', 'DESATIVADO'))
);

CREATE INDEX ix_ponto_auditoria_ponto ON ponto_auditoria (tenant_id, ponto_id, ocorrido_em);
